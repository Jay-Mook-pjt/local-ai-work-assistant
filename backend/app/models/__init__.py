"""SQLAlchemy ORM models.

Tables: meetings, audio_files, jobs, transcripts, meeting_minutes, action_items,
email_history (as specified) + documents (generated DOCX files, used in PHASE 5).
"""

import uuid
from datetime import UTC, date, datetime
from typing import Any

from sqlalchemy import JSON, Boolean, Date, DateTime, Float, ForeignKey, Integer, String, Text, TypeDecorator
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.session import Base


def new_id() -> str:
    return uuid.uuid4().hex


def utcnow() -> datetime:
    return datetime.now(UTC)


class UTCDateTime(TypeDecorator):
    """Stores naive UTC in SQLite, always returns timezone-aware UTC datetimes."""

    impl = DateTime
    cache_ok = True

    def process_bind_param(self, value: datetime | None, dialect: Any) -> datetime | None:
        if value is None:
            return None
        if value.tzinfo is None:
            raise ValueError("naive datetime is not allowed; use timezone-aware UTC")
        return value.astimezone(UTC).replace(tzinfo=None)

    def process_result_value(self, value: datetime | None, dialect: Any) -> datetime | None:
        return value.replace(tzinfo=UTC) if value is not None else None


class Meeting(Base):
    __tablename__ = "meetings"

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    title: Mapped[str] = mapped_column(String(200), index=True)
    meeting_date: Mapped[date] = mapped_column(Date, index=True)
    attendees: Mapped[list[str]] = mapped_column(JSON, default=list)
    purpose: Mapped[str] = mapped_column(Text, default="")
    agenda: Mapped[list[str]] = mapped_column(JSON, default=list)
    instructions: Mapped[str] = mapped_column(Text, default="")
    # Mirrors the latest job's status for fast list filtering. PENDING until audio arrives.
    status: Mapped[str] = mapped_column(String(20), default="PENDING", index=True)
    latest_job_id: Mapped[str | None] = mapped_column(String(32), nullable=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow, index=True)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow, onupdate=utcnow)

    audio: Mapped["AudioFile | None"] = relationship(back_populates="meeting", cascade="all, delete-orphan", uselist=False)
    jobs: Mapped[list["Job"]] = relationship(back_populates="meeting", cascade="all, delete-orphan", order_by="Job.created_at")
    transcript: Mapped["Transcript | None"] = relationship(cascade="all, delete-orphan", uselist=False)
    minutes: Mapped["MeetingMinutes | None"] = relationship(cascade="all, delete-orphan", uselist=False)
    action_items: Mapped[list["ActionItem"]] = relationship(cascade="all, delete-orphan", order_by="ActionItem.position")
    documents: Mapped[list["Document"]] = relationship(cascade="all, delete-orphan", order_by="Document.created_at.desc()")
    emails: Mapped[list["EmailHistory"]] = relationship(cascade="all, delete-orphan", order_by="EmailHistory.sent_at.desc()")


class AudioFile(Base):
    __tablename__ = "audio_files"

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    meeting_id: Mapped[str] = mapped_column(ForeignKey("meetings.id", ondelete="CASCADE"), unique=True)
    original_filename: Mapped[str] = mapped_column(String(255))
    # Paths are relative to STORAGE_DIR and generated by the server (never from user input).
    stored_path: Mapped[str] = mapped_column(String(500))
    processed_path: Mapped[str | None] = mapped_column(String(500), nullable=True)
    size_bytes: Mapped[int] = mapped_column(Integer)
    mime_type: Mapped[str] = mapped_column(String(100))
    format_name: Mapped[str] = mapped_column(String(100), default="")
    duration_seconds: Mapped[float | None] = mapped_column(Float, nullable=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow)

    meeting: Mapped[Meeting] = relationship(back_populates="audio")


class Job(Base):
    __tablename__ = "jobs"

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    meeting_id: Mapped[str] = mapped_column(ForeignKey("meetings.id", ondelete="CASCADE"), index=True)
    status: Mapped[str] = mapped_column(String(20), default="PENDING", index=True)
    llm_model: Mapped[str | None] = mapped_column(String(200), nullable=True)
    # Run speech recognition again even if a transcript of this audio exists.
    retranscribe: Mapped[bool | None] = mapped_column(Boolean, nullable=True)
    progress: Mapped[int] = mapped_column(Integer, default=0)
    message: Mapped[str | None] = mapped_column(Text, nullable=True)
    error: Mapped[str | None] = mapped_column(Text, nullable=True)
    worker_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow, index=True)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow, onupdate=utcnow)
    started_at: Mapped[datetime | None] = mapped_column(UTCDateTime, nullable=True)
    finished_at: Mapped[datetime | None] = mapped_column(UTCDateTime, nullable=True)

    meeting: Mapped[Meeting] = relationship(back_populates="jobs")


class Transcript(Base):
    __tablename__ = "transcripts"

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    meeting_id: Mapped[str] = mapped_column(ForeignKey("meetings.id", ondelete="CASCADE"), unique=True)
    # Which upload this transcript belongs to; a re-analysis of the same audio reuses it.
    audio_file_id: Mapped[str | None] = mapped_column(String(32), nullable=True)
    language: Mapped[str] = mapped_column(String(10))
    model: Mapped[str] = mapped_column(String(200))
    segments: Mapped[list[dict[str, Any]]] = mapped_column(JSON, default=list)
    full_text: Mapped[str] = mapped_column(Text, default="")  # for content search
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow)


class MeetingMinutes(Base):
    __tablename__ = "meeting_minutes"

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    meeting_id: Mapped[str] = mapped_column(ForeignKey("meetings.id", ondelete="CASCADE"), unique=True)
    meeting_summary: Mapped[str] = mapped_column(Text, default="")
    discussion_items: Mapped[list[dict[str, Any]]] = mapped_column(JSON, default=list)
